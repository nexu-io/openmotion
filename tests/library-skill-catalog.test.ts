test('repository MCP index and details include all Skills without polluting galleries or recommendations', async t => {
  const dir = await mkdtemp(path.join(tmpdir(), 'skill-index-'));
  t.after(() => rm(dir, { recursive: true, force: true }));
  const catalogRoot = path.join(dir, 'catalog');
  await mkdir(path.join(catalogRoot, 'sample/source'), { recursive: true });
  await writeFile(path.join(catalogRoot, 'catalog.json'), JSON.stringify({ schemaVersion: 1, templateIds: ['sample'], publication: { defaultLocale: 'en', locales: ['en'] } }));
  await writeFile(path.join(catalogRoot, 'sample/template.json'), JSON.stringify({ templateId: 'sample', entry: { templateId: 'sample', original: { templateName: 'Sample' }, files: [] }, locales: { en: {} } }));
  await writeFile(path.join(catalogRoot, 'sample/source/manifest.json'), '{}');
  const catalog = new TemplateCatalog(dir, { source: 'repository', repositoryRoot: catalogRoot });
  const skills = await loadLibrarySkills();
  const skillDirs = (await readdir(path.join(process.cwd(), 'library/skills'), { withFileTypes: true })).filter(entry => entry.isDirectory() && existsSync(path.join(process.cwd(), 'library/skills', entry.name, 'SKILL.md')));
  assert(skills.length > 0);
  assert.equal(skills.length, skillDirs.length);
  const index = await catalog.index();
  const rows = (await readFile(index.indexPath, 'utf8')).trim().split('\n').map(line => JSON.parse(line));
  assert.equal(rows.filter(row => row.kind === 'skill').length, skills.length);
  assert.equal(new Set(rows.map(row => row.templateId)).size, rows.length);
  const id = 'openmotion-design-remix';
  const detail = await catalog.detail(id);
  assert.equal(detail.instructions, await readFile(path.join(detail.localSource as string, 'SKILL.md'), 'utf8'));
  assert(detail.files.includes('SKILL.md'));
  for (const file of detail.files) {
    if (existsSync(path.join(detail.localSource as string, file))) continue;
    const object = detail.objects?.find((object: { path: string }) => object.path === file);
    assert(object?.url, 'Missing local supporting files must expose their immutable download URL: ' + file);
  }
  assert.match(JSON.stringify(detail.workflowGuide), /natural_language/);
  assert(!JSON.stringify(detail.workflowGuide).includes('apply_template'));
  const page = await catalog.page();
  assert(!JSON.stringify(page).includes('"kind":"skill"'));
  assert(skills.every(skill => !recommendationTemplateIds.includes(skill.id as never)));
  await assert.rejects(catalog.get(id), /Skills are instructions/);
  await assert.rejects(callTool('motion_apply_template', { templateId: id, expectedRevision: 'a'.repeat(64) }), /Skills are instructions/);
  const service = new Phase1Service(new WorkspaceStore(dir), process.cwd(), {} as any);
  await assert.rejects(service.call('openmotion_create_project', { requestId: 'skill-reject', projectType: 'template', templateId: id, title: 'Skill', requirements: 'Create a film' }), /Skills are instructions/);
  assert.throws(() => assertSkillIds(skills, [id]), /Duplicate/);
});

test('uncarded Skills use frontmatter and hosted publication preserves instructions without local paths', async t => {
  const root = await mkdtemp(path.join(tmpdir(), 'skill-hosted-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  await mkdir(path.join(root, 'library/skills/uncarded/references'), { recursive: true });
  await writeFile(path.join(root, 'library/skills/uncarded/SKILL.md'), '---\nname: Uncarded\ndescription: >-\n  Use this\n  for stories\n---\n# Instructions');
  await writeFile(path.join(root, 'library/skills/uncarded/references/example.md'), 'reference');
  const remoteVideo = { path: 'library/skills/uncarded/assets/demo.mp4', bytes: 4, sha256: 'b'.repeat(64), url: 'https://releases.open-design.ai/open-motion/media/sha256/' + 'b'.repeat(64) + '.mp4' };
  await writeFile(path.join(root, 'repository-media.json'), JSON.stringify({ schemaVersion: 1, files: [remoteVideo] }));
  const skills = await loadLibrarySkills(root, false);
  const local = (await loadLibrarySkills(root))[0];
  assert.equal(local.localSource, path.join(root, 'library/skills/uncarded'));
  assert.deepEqual(local.objects, [{ ...remoteVideo, path: 'assets/demo.mp4' }]);
  await mkdir(path.join(local.localSource!, 'assets'), { recursive: true });
  await writeFile(path.join(local.localSource!, 'assets/demo.mp4'), 'restored media');
  assert.equal((await loadLibrarySkills(root))[0].objects, undefined, 'Restored files use the local filesystem');
  await rm(path.join(local.localSource!, 'assets/demo.mp4'));
  assert.equal(skills[0].title, 'Uncarded');
  assert.equal(skills[0].description, 'Use this for stories');
  assert.equal(skills[0].localSource, undefined);
  assert(skills[0].files.includes('references/example.md'));
  assert(skills[0].files.includes('assets/demo.mp4'));
  const manifest = { schemaVersion: 1, commit: 'a'.repeat(40), templateIds: ['sample'], skills, publication: { defaultLocale: 'en', locales: ['en'] } };
  const record = { templateId: 'sample', entry: { templateId: 'sample', original: { templateName: 'Sample' }, files: [] }, locales: { en: {} } };
  const templateRoot = path.join(root, 'library/templates/catalog/sample');
  await mkdir(templateRoot, { recursive: true });
  await writeFile(path.join(root, 'library/templates/catalog/catalog.json'), JSON.stringify(manifest));
  await writeFile(path.join(templateRoot, 'template.json'), JSON.stringify(record));
  const built = await buildTemplatePublication(root, manifest.commit);
  t.after(() => rm(built.staging, { recursive: true, force: true }));
  assert.deepEqual(built.catalog.skills.map(({ objects: _objects, ...skill }: { objects?: unknown }) => skill), skills);
  const request = async (url: any) => new Response(JSON.stringify(String(url).endsWith('/template.json') ? record : built.catalog));
  const hosted = await loadHostedCatalog(request as typeof fetch);
  const catalog = new TemplateCatalog(root, { source: 'hosted', fetch: request as typeof fetch });
  const detail = await catalog.detail('uncarded');
  assert.equal(detail.instructions, skills[0].instructions);
  assert.equal(detail.localSource, undefined);
  const object = detail.objects?.find((file: { path: string }) => file.path === 'references/example.md');
  assert.equal(object?.sha256, createHash('sha256').update('reference').digest('hex'));
  assert.equal(object?.url, `${hosted.objectBaseUrl}/${object?.sha256}`);
  assert(built.uploads.some(upload => upload.object && upload.key.endsWith('/objects/' + object?.sha256)));
  const remote = detail.objects?.find((file: { path: string }) => file.path === 'assets/demo.mp4');
  assert.equal(remote?.url, remoteVideo.url);
  assert.equal(built.uploads.some(upload => upload.object && upload.key.endsWith('/objects/' + remoteVideo.sha256)), false);
  assert.match(detail.workflowGuide.nextStep, /sha256/);
  await assert.rejects(catalog.get('uncarded'), /Skills are instructions/);
  assert.deepEqual(restoreHostedCatalog(JSON.parse(serializeHostedCatalog(hosted)), request as typeof fetch).skills, hosted.skills);
});
